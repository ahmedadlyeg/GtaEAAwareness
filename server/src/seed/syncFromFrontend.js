'use strict';
/**
 * Sync the server with the front-end content (single source of truth = /js/data).
 *
 *   npm run sync:content
 *
 * 1. Builds src/seed/questions.json from js/data/content.js + js/data/quiz.js
 *    + js/data/kb.js (EA modules = track 'ea', TOGAF topics = track 'togaf',
 *    knowledge-base articles = "kb:<id>" with track 'kbf' | 'kbp' | 'kba' by
 *    level; exam parts with level and questions_per_attempt; answer keys) and
 *    upserts it. The old virtual
 *    'togaf' module is deactivated because it is no longer in the list.
 * 2. Deactivates any module / round / question not present in the front end
 *    (e.g. the placeholder seed rows in db/schema.*.sql).
 * 3. Publishes the sign-off statement from content.js as the active statement,
 *    hashed exactly as the browser hashes it: SHA-256 of
 *    title + "\n" + body.join("\n").
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const { seedQuestions } = require('./seedQuestions');

const FRONT = path.resolve(__dirname, '../../../js/data');

function loadFrontend() {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  for (const f of ['content.js', 'quiz.js', 'kb.js']) {
    vm.runInContext(fs.readFileSync(path.join(FRONT, f), 'utf8'), sandbox, { filename: f });
  }
  return { content: sandbox.window.EA_CONTENT, quiz: sandbox.window.EA_QUIZ, kb: sandbox.window.KB_ARTICLES || [] };
}

function answerKey(q) {
  if (q.type === 'mcq' || q.type === 'truefalse') return { answer: q.answer };
  if (q.type === 'order') return { items: q.items };
  if (q.type === 'match') return { pairs: q.pairs };
  if (q.type === 'categorize') return { items: q.items };
  throw new Error(`Unsupported type ${q.type} (${q.id})`);
}

const KB_TRACK = { Foundation: 'kbf', Practitioner: 'kbp', Advanced: 'kba' };

function build({ content, quiz, kb = [] }) {
  // EA Foundation modules (track 'ea') + TOGAF topics (track 'togaf'); both count towards exam eligibility.
  const modules = content.modules
    .filter((m) => !m.virtual)
    .map((m, i) => ({ id: m.id, title: m.title, mandatory: !!m.mandatory, track: 'ea', version: 1, sortOrder: (i + 1) * 10 }));
  (content.togafTopics || []).forEach((t, i) => {
    modules.push({ id: t.id, title: `TOGAF · ${t.title}`, mandatory: true, track: 'togaf', version: 1, sortOrder: 500 + (i + 1) * 10 });
  });
  // Knowledge-base articles: tracked (Practitioner / Advanced paths), never mandatory. Optional reading -> 'kbf' (counts toward no path).
  kb.forEach((a, i) => {
    modules.push({ id: `kb:${a.id}`, title: `KB · ${a.title}`.slice(0, 200), mandatory: false, track: a.optional ? 'kbf' : (KB_TRACK[a.level] || 'kbf'), version: 1, sortOrder: 1000 + (i + 1) * 10 });
  });
  const roundOf = {};
  quiz.rounds.forEach((r) => r.q.forEach((id) => { roundOf[id] = r.id; }));
  return {
    _readme: ['Generated by src/seed/syncFromFrontend.js from js/data — do not edit by hand.'],
    deactivateMissing: true,
    modules,
    rounds: quiz.rounds.map((r, i) => ({ id: r.id, title: r.part ? `Part ${r.part} · ${r.title}` : r.title, mandatory: !!r.mandatory, passPct: 70, questionsPerAttempt: r.perAttempt || null, level: r.level || 'foundation', sortOrder: (i + 1) * 10 })),
    questions: quiz.questions.map((q) => ({ id: q.id, roundId: roundOf[q.id], tag: q.tag, type: q.type, prompt: q.q, points: q.points, answerKey: answerKey(q) })),
  };
}

async function sync(db) {
  const fe = loadFrontend();
  const data = build(fe);
  fs.writeFileSync(path.join(__dirname, 'questions.json'), JSON.stringify(data, null, 2) + '\n');
  const stats = await seedQuestions(db, data);

  const keepM = data.modules.map((m) => m.id);
  const keepR = data.rounds.map((r) => r.id);
  const keepQ = data.questions.map((q) => q.id);
  const S = fe.content.signoff;
  const text = S.title + '\n' + S.body.join('\n');
  const sha = crypto.createHash('sha256').update(text, 'utf8').digest('hex');
  await db.tx(async (t) => {
    for (const r of await t.all('SELECT id FROM content_modules WHERE active = 1')) if (!keepM.includes(r.id)) await t.run('UPDATE content_modules SET active = 0 WHERE id = @id', { id: r.id });
    for (const r of await t.all('SELECT id FROM quiz_rounds WHERE active = 1')) if (!keepR.includes(r.id)) await t.run('UPDATE quiz_rounds SET active = 0 WHERE id = @id', { id: r.id });
    for (const r of await t.all('SELECT id FROM questions WHERE active = 1')) if (!keepQ.includes(r.id)) await t.run('UPDATE questions SET active = 0 WHERE id = @id', { id: r.id });
    await t.run('UPDATE signoff_statements SET active = 0 WHERE version <> @v', { v: S.version });
    const exists = await t.get('SELECT version FROM signoff_statements WHERE version = @v', { v: S.version });
    if (exists) await t.run('UPDATE signoff_statements SET title = @title, body_markdown = @body, sha256 = @sha, active = 1 WHERE version = @v', { v: S.version, title: S.title, body: text, sha });
    else await t.run('INSERT INTO signoff_statements (version, title, body_markdown, sha256, active) VALUES (@v, @title, @body, @sha, 1)', { v: S.version, title: S.title, body: text, sha });
  });
  return { ...stats, statement: S.version, sha256: sha };
}

if (require.main === module) {
  (async () => {
    const { bootstrap } = require('../bootstrap');
    const { db } = await bootstrap();
    console.log('sync:content', await sync(db));
    await db.close();
  })().catch((e) => { console.error(e); process.exit(1); });
}

module.exports = { sync, build, loadFrontend };
